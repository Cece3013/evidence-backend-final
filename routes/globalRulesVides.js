const NOYAU_BIEN_VIDE = `NOYAU BIEN VIDE — VERSION APPLICATION V1
ÉVIDENCE HOME STAGING
RÔLE
Ce noyau définit les règles générales de home staging applicables à tous les biens vides ou quasi vides.
Il est utilisé APRÈS :
• l’analyse des photographies ;
• l’identification des contraintes réelles ;
• la décision concernant le mobilier résiduel ;
• la décision et le verrouillage de l’implantation.
Il ne doit donc PAS recalculer l’organisation spatiale de la pièce.
Les données issues du plan d’implantation verrouillé sont prioritaires.
——————————————————————————————————————————
1 — OBJECTIF DU HOME STAGING
Créer un aménagement immobilier :
• photoréaliste ;
• crédible ;
• chaleureux ;
• lumineux ;
• fonctionnel ;
• contemporain sans être trop marqué ;
• suffisamment neutre pour convenir au plus grand nombre ;
• vendeur sans devenir artificiel ;
• réellement reproductible dans le logement.
L’objectif n’est pas de créer un projet de décoration spectaculaire.
L’objectif est de permettre à un acquéreur de :
• comprendre immédiatement la fonction de la pièce ;
• percevoir ses volumes ;
• comprendre son potentiel ;
• se projeter facilement ;
• conserver une perception réaliste du bien mis en vente.
Le logement doit rester l’élément principal de l’image.
Le mobilier sert le logement.
Le mobilier ne doit jamais prendre le dessus sur le logement.
——————————————————————————————————————————

2 — PRINCIPE DE SOBRIÉTÉ
Meubler suffisamment pour rendre la fonction évidente.
Ne pas surmeubler.
Ne pas chercher à occuper chaque espace vide.
Conserver des zones de respiration.
Éviter :
• accumulation de meubles ;
• accumulation d’accessoires ;
• multiplication de petits éléments décoratifs ;
• composition trop scénarisée ;
• ambiance de catalogue ;
• décoration trop personnelle ;
• effet showroom ;
• effet hôtel de luxe.
Chaque élément ajouté doit avoir une utilité :
• fonctionnelle ;
• visuelle ;
• ou de mise en valeur du volume.
Si un élément n’apporte rien à la compréhension ou à la valorisation du bien :
NE PAS L’AJOUTER.
——————————————————————————————————————————
3 — MOBILIER
Utiliser du mobilier :
• courant ;
• crédible ;
• accessible ;
• contemporain ;
• intemporel ;
• proportionné à la pièce ;
• visuellement léger lorsque le volume est réduit.
Éviter :
• mobilier monumental ;
• meubles excessivement design ;
• mobilier luxueux disproportionné au bien ;
• formes trop originales ;
• meubles artificiellement petits pour les faire entrer dans l’espace ;
• accumulation de meubles secondaires.
Les meubles doivent avoir des dimensions réalistes.

Le résultat doit pouvoir être reproduit physiquement dans le logement.
——————————————————————————————————————————
4 — STYLE GÉNÉRAL ÉVIDENCE
Créer une ambiance :
• neutre ;
• chaleureuse ;
• élégante ;
• naturelle ;
• contemporaine ;
• intemporelle.
Influences possibles, avec beaucoup de sobriété :
• méditerranéenne ;
• bohème chic ;
• scandinave ;
• contemporaine naturelle.
Ne jamais pousser une influence stylistique au point de transformer le logement en décor thématique.
——————————————————————————————————————————
5 — PALETTE
Privilégier :
• blanc cassé ;
• crème ;
• beige ;
• sable ;
• lin ;
• écru ;
• taupe clair ;
• bois naturel.
Possibilité d’ajouter avec parcimonie :
• terracotta ;
• brun chaud ;
• vert végétal ;
• noir mat discret.
Éviter :
• couleurs très saturées ;
• contrastes agressifs ;
• accumulation de couleurs ;
• palettes trop tendance ou rapidement datables.
L’ensemble doit rester lumineux et harmonieux.
——————————————————————————————————————————

6 — MATIÈRES
Privilégier des matières naturelles ou d’apparence naturelle :
• bois clair ;
• lin ;
• coton ;
• laine ;
• fibres naturelles ;
• rotin ;
• cannage ;
• céramique ;
• verre ;
• pierre ;
• métal noir mat en petites touches.
Varier subtilement les textures pour créer de la chaleur.
Ne pas accumuler les matières décoratives.
——————————————————————————————————————————
7 — TEXTILES
Les textiles peuvent être utilisés pour apporter :
• chaleur ;
• douceur ;
• confort visuel ;
• projection.
Selon la pièce et lorsque le module correspondant l’autorise :
• tapis ;
• voilages ;
• coussins ;
• plaid ;
• linge de lit.
Les textiles doivent rester :
• sobres ;
• peu nombreux ;
• harmonieux ;
• réalistes ;
• correctement dimensionnés.
Éviter les motifs très marqués.
——————————————————————————————————————————
8 — DÉCORATION
Utiliser une décoration légère et immobilière.

Possibilités :
• quelques cadres ;
• miroir ;
• vase ;
• livres ;
• petite céramique ;
• plante ;
• luminaire ;
• petit objet décoratif.
Ne pas chercher à remplir toutes les surfaces.
Éviter :
• multiplication des cadres ;
• accumulation de plantes ;
• bibliothèques excessivement décorées ;
• nombreux bibelots ;
• compositions décoratives complexes ;
• objets trop personnels.
Le niveau de décoration doit donner l’impression :
D’UN LOGEMENT SOIGNÉ ET PRÊT À ÊTRE VISITÉ,
et non :
D’UN LOGEMENT MIS EN SCÈNE POUR UNE PUBLICITÉ DE DÉCORATION.
——————————————————————————————————————————
9 — PLANTES
Les plantes peuvent apporter vie et chaleur mais doivent rester secondaires.
Utiliser :
• une plante importante lorsque cela apporte réellement quelque chose ;
ou
• quelques petites touches végétales.
Ne pas créer une accumulation végétale.
Une plante ne doit jamais être ajoutée uniquement pour combler un espace vide.
Elle doit respecter toutes les zones interdites et contraintes transmises par l’étape d’implantation.
——————————————————————————————————————————
10 — LUMINAIRES
Les luminaires peuvent contribuer à rendre la pièce chaleureuse et réaliste.
Selon la pièce :

• suspension ;
• lampe à poser ;
• lampadaire ;
• lampe de chevet.
Éviter :
• multiplication des sources ;
• luminaires surdimensionnés ;
• design spectaculaire ;
• éclairage artificiel excessif.
Conserver une lumière cohérente avec la photographie d’origine.
——————————————————————————————————————————
11 — RAFRAÎCHISSEMENT COSMÉTIQUE
Le home staging peut inclure un rafraîchissement cosmétique léger lorsque l’état visible du logement gêne fortement la
projection.
Peuvent notamment être harmonisés lorsque cela est réellement nécessaire :
• mur très daté ;
• peinture fortement dégradée ;
• papier peint ancien très marqué ;
• revêtement de sol très dégradé ou fortement daté.
Les interventions doivent rester :
• réalistes ;
• simples ;
• économiquement plausibles ;
• compatibles avec une préparation du logement à la vente.
Exemples :
• peinture neutre claire ;
• remplacement visuel d’une moquette très datée par un sol clair plausible ;
• harmonisation d’un mur trop marqué.
NE PAS effectuer un projet de rénovation architecturale.
——————————————————————————————————————————
12 — ÉLÉMENTS DE CARACTÈRE
Préserver et valoriser les éléments authentiques présentant un intérêt immobilier.
Exemples :
• parquet ancien ;
• tomettes ;
• terrazzo ;
• pierre ;
• cheminée ;

• moulures ;
• rosaces ;
• poutres ;
• boiseries architecturales ;
• carreaux anciens valorisants ;
• autre élément caractéristique du logement.
Ne pas remplacer systématiquement un élément ancien simplement parce qu’il n’est pas contemporain.
ANCIEN ≠ À SUPPRIMER.
Un élément ancien valorisant doit être intégré harmonieusement au home staging.
——————————————————————————————————————————
13 — COHÉRENCE AVEC LE BIEN
Toujours adapter le niveau d’aménagement :
• à la superficie ;
• au type de logement ;
• à son époque ;
• à son architecture ;
• à son standing réel ;
• au marché immobilier auquel il appartient.
Un appartement standard ne doit pas devenir visuellement un appartement de luxe.
Un petit logement ne doit pas recevoir le mobilier d’un grand séjour.
Un logement ancien ne doit pas perdre tout son caractère.
Un logement contemporain ne doit pas être artificiellement vieilli.
Le home staging doit révéler le bien existant, pas en fabriquer un autre.
——————————————————————————————————————————
14 — RÉALISME PHOTOGRAPHIQUE
Le résultat doit ressembler à une véritable photographie immobilière.
Le mobilier ajouté doit présenter :
• perspective correcte ;
• échelle cohérente ;
• ombres cohérentes ;
• contacts réalistes avec le sol ;
• éclairage cohérent ;
• textures crédibles.
Éviter absolument :
• effet rendu 3D ;
• effet CGI ;
• meubles flottants ;

• perspectives déformées ;
• mobilier disproportionné ;
• textures artificielles ;
• lumière irréaliste ;
• rendu trop parfait ;
• surexposition ;
• effet catalogue.
——————————————————————————————————————————
15 — HIÉRARCHIE DES OBJECTIFS MÉTIER
Lors de la sélection du mobilier, des matières et de la décoration, rechercher dans cet ordre :
1. compréhension de la fonction ;
2. respect du volume disponible ;
3. projection de l’acquéreur ;
4. valorisation du logement ;
5. équilibre visuel ;
6. chaleur ;
7. décoration.
Ne jamais sacrifier le réalisme pour obtenir une image plus spectaculaire.
——————————————————————————————————————————
16 — RELATION AVEC LES AUTRES BLOCS DE L’APPLICATION
Ce noyau définit les RÈGLES GÉNÉRALES DE HOME STAGING.
Il ne décide pas :
• si les photos sont suffisantes ;
• de l’emplacement du mobilier principal ;
• des circulations ;
• des zones interdites ;
• de la suppression ou conservation du mobilier résiduel.
Ces décisions ont déjà été prises avant la génération.
Le MODULE PIÈCE complète ce noyau avec les règles spécifiques :
• au salon ;
• au salon / salle à manger ;
• à la cuisine ;
• à la chambre parentale ;
• à la chambre enfant ;
• à la chambre adolescent ;
• à la salle de bain ;
• à l’extérieur ;
• etc.
Les MICRO-MODULES ajoutent uniquement des besoins ponctuels validés par l’application.
——————————————————————————————————————————

PRINCIPE FINAL
HOME STAGING, PAS RÉNOVATION COMPLÈTE.
VALORISER, PAS TRANSFORMER LE BIEN.
MEUBLER, PAS REMPLIR.
RÉCHAUFFER, PAS SURDÉCORER.
MODERNISER AVEC MESURE.
CONSERVER LE CARACTÈRE LORSQU’IL A DE LA VALEUR.
UTILISER DU MOBILIER RÉALISTE ET PROPORTIONNÉ.
CRÉER UNE IMAGE VENDEUSE MAIS CRÉDIBLE.
LE LOGEMENT RESTE TOUJOURS LE SUJET PRINCIPAL.`;

